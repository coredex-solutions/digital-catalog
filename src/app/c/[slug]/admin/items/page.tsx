function ItemsPageContent() {
  const { slug, user, fetchWithAuth, features } = useCatalogAdmin();
  const isViewer = user?.role === 'viewer';
  const t = useCopy({ en, ar });
  const lang = useAdminLang();
  const f = useFormat();

  const [items, setItems] = useState<Item[]>([]);
  const [categories, setCategories] = useState<Category[]>([]);
  const [loading, setLoading] = useState(true);
  const [showModal, setShowModal] = useState(false);
  const [editingItem, setEditingItem] = useState<Item | null>(null);
  const [saving, setSaving] = useState(false);

  const [filterCategory, setFilterCategory] = useState<string>("");
  const [query, setQuery] = useState("");
  /** The category whose dishes are being put in order (compact list with up/down buttons) */
  const [reorderCategory, setReorderCategory] = useState<string | null>(null);
  const [orderError, setOrderError] = useState<string | null>(null);
  // Saves of the dish order run one after another, in the order of the clicks
  const [enqueueOrderSave] = useState(() => {
    let queue: Promise<void> = Promise.resolve();
    return (task: () => Promise<void>) => {
      queue = queue.then(task);
    };
  });
  const [activeLang, setActiveLang] = useState<'en' | 'ar'>(features?.default_language === 'ar' ? 'ar' : 'en');

  const [formData, setFormData] = useState({
    category_id: "",
    name_ar: "",
    name_en: "",
    description_ar: "",
    description_en: "",
    price: "",
    currency: "USD",
    image_url: "",
    is_featured: false,
  });
  const [options, setOptions] = useState<OptionDraft[]>([]);
  const [dietary, setDietary] = useState<DietaryCode[]>([]);
  // Allergens are only saved once the owner confirms they checked them; otherwise unknown (null)
  const [allergensChecked, setAllergensChecked] = useState(false);
  const [allergens, setAllergens] = useState<AllergenCode[]>([]);
  const [saveError, setSaveError] = useState<string | null>(null);
  const [uploading, setUploading] = useState(false);
  const [uploadError, setUploadError] = useState<string | null>(null);

  /** The photo in the form was generated by AI (guests see "Illustrative image") */
  const [imageIllustrative, setImageIllustrative] = useState(false);

  // State is only set in the promise callbacks, once the requests have answered
  const fetchData = useCallback(async () => {
    // Runs after every save too: lets the shell refresh its "unpublished changes" bar
    window.dispatchEvent(new Event("menu-draft-changed"));
    const token = localStorage.getItem(`catalog_admin_token_${slug}`);
    if (!token) return;

    await Promise.all([
      fetchWithAuth(`/api/c/${slug}/admin/items/`),
      fetchWithAuth(`/api/c/${slug}/admin/categories/`),
    ])
      .then(async ([itemsRes, catsRes]) => {
        if (itemsRes.ok) {
          const data = await itemsRes.json();
          setItems(data.items);
        }
        if (catsRes.ok) {
          const data = await catsRes.json();
          setCategories(data.categories);
        }
      })
      .catch((error) => {
        console.error("Failed to fetch data:", error);
      })
      .finally(() => setLoading(false));
  }, [slug, fetchWithAuth]);

  useEffect(() => {
    fetchData();
  }, [fetchData, features]);

  // The form opens in the menu's default language (again if the plan's settings change)
  const [langFeatures, setLangFeatures] = useState(features);
  if (langFeatures !== features) {
    setLangFeatures(features);
    if (features) {
      setActiveLang(features.default_language === 'ar' ? 'ar' : 'en');
    }
  }

  const openAddModal = () => {
    if (features && items.length >= features.max_items) {
      alert(t.limitReached(features.max_items));
      return;
    }
    setEditingItem(null);
    setFormData({
      category_id: categories[0]?.id || "",
      name_ar: "",
      name_en: "",
      description_ar: "",
      description_en: "",
      price: "",
      currency: "USD",
      image_url: "",
      is_featured: false,
    });
    setOptions([]);
    setDietary([]);
    setAllergensChecked(false);
    setAllergens([]);
    setImageIllustrative(false);
    setSaveError(null);
    setUploadError(null);
    setShowModal(true);
    setActiveLang('en');
  };

  const openEditModal = (item: Item) => {
    setEditingItem(item);
    setFormData({
      category_id: item.category_id,
      name_ar: item.name_ar,
      name_en: item.name_en,
      description_ar: item.description_ar || "",
      description_en: item.description_en || "",
      price: String(Number(item.price) || 0),
      currency: item.currency,
      image_url: item.image_url || "",
      is_featured: Boolean(item.is_featured),
    });
    setOptions((item.variants || []).map((v) => ({ id: v.id, name_en: v.name_en, name_ar: v.name_ar, price: String(v.price) })));
    setDietary(item.dietary || []);
    setAllergensChecked(item.allergens != null);
    setAllergens(item.allergens || []);
    setImageIllustrative(Boolean(item.image_is_illustrative));
    setSaveError(null);
    setUploadError(null);
    setShowModal(true);
    setActiveLang('en');
  };

  const handleSave = async () => {
    const hasOptions = options.length > 0;
    // Say what is missing instead of doing nothing
    const missing = !formData.name_en.trim() && !formData.name_ar.trim()
      ? t.nameRequired
      : !formData.category_id
        ? t.categoryRequired
        : !hasOptions && !formData.price
          ? t.priceRequired
          : null;
    if (missing) {
      setSaveError(missing);
      return;
    }

    setSaving(true);
    setSaveError(null);

    const body = {
      ...formData,
      // With options, the API sets the dish price to the cheapest option
      price: hasOptions ? undefined : parseFloat(formData.price),
      // Never copy English over existing translations; the API falls back to English for empty fields
      name_ar: formData.name_ar,
      description_ar: formData.description_ar,
      variants: options.map((o) => ({ id: o.id, name_en: o.name_en.trim(), name_ar: o.name_ar.trim(), price: o.price })),
      dietary,
      allergens: allergensChecked ? allergens : null,
    };

    try {
      const url = editingItem
        ? `/api/c/${slug}/admin/items/${editingItem.id}/`
        : `/api/c/${slug}/admin/items/`;

      const res = await fetchWithAuth(url, {
        method: editingItem ? "PUT" : "POST",
        headers: {
          "Content-Type": "application/json",
        },
        body: JSON.stringify(body),
      });

      if (res.ok) {
        setShowModal(false);
        fetchData();
      } else {
        const data = await res.json().catch(() => null);
        setSaveError(data?.error || t.saveFailed);
      }
    } catch (error) {
      console.error("Failed to save item:", error);
      setSaveError(t.offline);
    } finally {
      setSaving(false);
    }
  };

  // One-tap "sold out" switch, so owners don't have to open the full edit form
  const toggleAvailability = async (item: Item) => {
    const available = item.is_available !== 0;
    const setAvailable = (value: number) =>
      setItems((prev) => prev.map((i) => (i.id === item.id ? { ...i, is_available: value } : i)));
    setAvailable(available ? 0 : 1);
    try {
      const res = await fetchWithAuth(`/api/c/${slug}/admin/items/${item.id}/`, {
        method: "PUT",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ is_available: !available }),
      });
      if (!res.ok) throw new Error(`HTTP ${res.status}`);
    } catch (error) {
      console.error("Failed to update availability:", error);
      setAvailable(available ? 1 : 0);
      alert(t.availabilityFailed);
    }
  };

  const handleDelete = async (id: string) => {
    const target = items.find((i) => i.id === id);
    const targetName = pickName(target, lang);
    if (!confirm(targetName ? t.deleteConfirm(targetName) : t.deleteConfirmUnnamed)) return;

    try {
      const res = await fetchWithAuth(`/api/c/${slug}/admin/items/${id}/`, {
        method: "DELETE",
      });

      if (res.ok) {
        fetchData();
      } else {
        const data = await res.json().catch(() => null);
        alert(data?.error || t.deleteFailed);
      }
    } catch {
      alert(t.deleteFailed);
    }
  };

  const handleImageUpload = async (e: React.ChangeEvent<HTMLInputElement>) => {
    const file = e.target.files?.[0];
    if (!file) return;

    setUploading(true);
    setUploadError(null);

    const formDataUpload = new FormData();
    formDataUpload.append("file", file);

    try {
      const res = await fetchWithAuth(`/api/c/${slug}/admin/upload/`, {
        method: "POST",
        body: formDataUpload,
      });

      const data = await res.json();

      if (res.ok) {
        setFormData((prev) => ({ ...prev, image_url: data.url }));
        setImageIllustrative(false);
      } else {
        setUploadError(data.error || t.uploadFailed);
      }
    } catch {
      setUploadError(t.uploadFailed);
    } finally {
      setUploading(false);
    }
  };


  // Search and category filter; dishes are shown grouped by category in guest-menu order
  const searching = query.trim().length > 0;
  const visibleItems = items.filter(
    (item) => (!filterCategory || item.category_id === filterCategory) && matchesQuery({ name_en: item.name_en, name_ar: item.name_ar }, query)
  );
  const knownCategory = new Set(categories.map((c) => c.id));
  const sections = [
    ...categories.map((cat) => ({ id: cat.id, name: pickName(cat, lang), items: visibleItems.filter((i) => i.category_id === cat.id) })),
    { id: "", name: t.noCategory, items: visibleItems.filter((i) => !knownCategory.has(i.category_id)) },
  ].filter((section) => section.items.length > 0);

  // Move a dish one place up or down within its category. Shown at once; saved in order of
  // the clicks so quick taps can't arrive out of sequence.
  const moveItem = (categoryId: string, itemId: string, delta: -1 | 1) => {
    const list = items.filter((i) => i.category_id === categoryId);
    const from = list.findIndex((i) => i.id === itemId);
    const to = from + delta;
    if (from < 0 || to < 0 || to >= list.length) return;
    const reordered = [...list];
    [reordered[from], reordered[to]] = [reordered[to], reordered[from]];
    setItems((prev) => {
      const queue = [...reordered];
      return prev.map((i) => (i.category_id === categoryId ? queue.shift() ?? i : i));
    });
    keepFocusOnRow(itemId, to, list.length, delta);
    setOrderError(null);
    const order = reordered.map((i) => i.id);
    enqueueOrderSave(async () => {
      try {
        const res = await fetchWithAuth(`/api/c/${slug}/admin/items/`, {
          method: "PUT",
          headers: { "Content-Type": "application/json" },
          body: JSON.stringify({ categoryId, order }),
        });
        if (!res.ok) {
          const data = await res.json().catch(() => null);
          throw new Error(data?.error || t.orderFailed);
        }
        window.dispatchEvent(new Event("menu-draft-changed"));
      } catch (error) {
        // A network failure (TypeError) has a browser message in English: show our own text
        setOrderError(error instanceof Error && !(error instanceof TypeError) ? error.message : t.orderFailed);
        fetchData();
      }
    });
  };

  return (
    <>
      <CatalogAdminHeader title={ADMIN_NAV_LABELS[lang].items}>
        <button
          onClick={openAddModal}
          disabled={isViewer}
          className="group relative flex items-center gap-3 px-6 py-3 bg-ui-primary text-ui-primary-fg rounded-control transition-all duration-500 font-semibold text-xs overflow-hidden shadow-lg disabled:opacity-50"
        >
          <div className="absolute inset-0 -translate-x-full group-hover:translate-x-full rtl:translate-x-full rtl:group-hover:-translate-x-full transition-transform duration-1000" />
          <Plus className="w-4 h-4" />
          {t.addDish}
        </button>
        {!isViewer && (
          <Link
            href={`/c/${slug}/admin/items/import/`}
            className="inline-flex min-h-11 items-center gap-2 rounded-control border border-ui-input bg-ui-surface px-5 text-xs font-semibold text-ui-ink hover:bg-ui-subtle"
          >
            <FileUp className="h-4 w-4" aria-hidden />
            {t.importDishes}
          </Link>
        )}
      </CatalogAdminHeader>

      <CatalogAdminContent>
        <div className="mb-6 sm:mb-10 flex flex-wrap items-center gap-3 sm:gap-6">
          <div className="relative w-full sm:w-80">
            <label htmlFor="dish-search" className="sr-only">
              {t.searchLabel}
            </label>
            <Search className="pointer-events-none absolute start-4 top-1/2 h-5 w-5 -translate-y-1/2 text-ui-muted" aria-hidden />
            <input
              id="dish-search"
              type="search"
              value={query}
              onChange={(e) => setQuery(e.target.value)}
              placeholder={t.searchPlaceholder}
              autoComplete="off"
              className="min-h-12 w-full rounded-control border border-ui-input bg-ui-surface ps-12 pe-4 text-base text-ui-ink placeholder:text-ui-muted focus:border-ui-primary"
            />
          </div>
          <div className="relative group">
            <select
              value={filterCategory}
              onChange={(e) => setFilterCategory(e.target.value)}
              aria-label={t.filterLabel}
              className="relative min-h-11 px-4 sm:px-6 py-3 sm:py-4 bg-ui-bg border border-ui-input rounded-control text-xs font-semibold text-ui-muted focus:outline-none focus:border-ui-primary transition-all appearance-none pe-12 cursor-pointer"
            >
              <option value="">{t.allCategories}</option>
              {categories.map((cat) => (
                <option key={cat.id} value={cat.id} className="bg-ui-surface">
                  {pickName(cat, lang)}
                </option>
              ))}
            </select>
          </div>
          <p className="text-sm text-ui-muted" aria-live="polite">
            {searching || filterCategory ? t.countFiltered(visibleItems.length, items.length) : t.count(items.length)}
          </p>
        </div>

        {orderError && (
          <p role="alert" className="mb-6 rounded-control border border-[#F3C7C7] bg-[#FEF2F2] px-4 py-3 text-sm font-medium text-ui-danger">
            {orderError}
          </p>
        )}

        {loading ? (
          <div className="grid grid-cols-1 md:grid-cols-2 lg:grid-cols-3 gap-4 sm:gap-8">
            {[...Array(6)].map((_, i) => (
              <div key={i} className="glass rounded-panel p-5 sm:p-8 h-40" />
            ))}
          </div>
        ) : items.length > 0 && visibleItems.length === 0 ? (
          <div className="rounded-panel border border-ui-line bg-ui-surface px-6 py-16 text-center">
            <Search className="mx-auto mb-4 h-10 w-10 text-ui-input" aria-hidden />
            <p className="font-medium text-ui-ink">{searching ? t.noMatch(query.trim()) : t.noneInCategory}</p>
            <button
              type="button"
              onClick={() => {
                setQuery("");
                setFilterCategory("");
              }}
              className="mt-4 min-h-11 rounded-control px-4 text-sm font-semibold text-ui-primary hover:bg-ui-subtle"
            >
              {t.showAll}
            </button>
          </div>
        ) : items.length === 0 ? (
          <div className="text-center py-32 glass rounded-panel border border-ui-line">
            <Package className="w-16 h-16 text-ui-line mx-auto mb-6" />
            <p className="text-xs font-semibold text-ui-muted">{t.empty}</p>
            <button
              onClick={openAddModal}
              className="mt-8 text-xs font-semibold text-ui-primary transition-transform"
            >
              {t.addFirst}
            </button>
            {!isViewer && (
              <p className="mt-3 text-sm text-ui-muted">
                <Link href={`/c/${slug}/admin/items/import/`} className="font-semibold text-ui-primary underline-offset-4 hover:underline">
                  {t.importHint}
                </Link>
              </p>
            )}
          </div>
        ) : (
          sections.map((section) => {
            const ordering = reorderCategory === section.id && !searching;
            const canOrder = !searching && !isViewer && section.id !== "" && section.items.length > 1;
            return (
          <section key={section.id || "other"} aria-labelledby={`section-${section.id || "other"}`} className="mb-10 sm:mb-14">
            <div className="mb-4 flex flex-wrap items-center justify-between gap-3">
              <h2 id={`section-${section.id || "other"}`} className="text-lg font-semibold">
                <bdi>{section.name}</bdi> <span className="text-sm font-normal text-ui-muted">· {f.number(section.items.length)}</span>
              </h2>
              {canOrder && (
                <button
                  type="button"
                  onClick={() => setReorderCategory(ordering ? null : section.id)}
                  aria-pressed={ordering}
                  className={`inline-flex min-h-11 items-center gap-2 rounded-control border px-4 text-sm font-medium transition-colors ${
                    ordering ? "border-ui-primary bg-ui-primary text-ui-primary-fg" : "border-ui-input text-ui-ink hover:bg-ui-subtle"
                  }`}
                >
                  {ordering ? <Check className="h-4 w-4" aria-hidden /> : <ArrowUpDown className="h-4 w-4" aria-hidden />}
                  {ordering ? t.done : t.changeOrder}
                </button>
              )}
            </div>
            {ordering ? (
              <>
                <ol className="divide-y divide-ui-line rounded-panel border border-ui-line bg-ui-surface">
                  {section.items.map((item, index) => {
                    const name = pickName(item, lang);
                    return (
                      <li key={item.id} className="flex items-center gap-3 px-3 py-2 sm:px-4">
                        <span className="w-6 text-center text-sm tabular-nums text-ui-muted">{index + 1}</span>
                        <span className="min-w-0 flex-1 truncate font-medium text-ui-ink"><bdi>{name}</bdi></span>
                        <button
                          type="button"
                          onClick={() => moveItem(section.id, item.id, -1)}
                          disabled={index === 0}
                          data-move={item.id}
                          data-dir="up"
                          aria-label={t.moveUp(name)}
                          className="flex h-11 w-11 items-center justify-center rounded-control border border-ui-line text-ui-ink hover:bg-ui-subtle disabled:opacity-30"
                        >
                          <ArrowUp className="h-5 w-5" aria-hidden />
                        </button>
                        <button
                          type="button"
                          onClick={() => moveItem(section.id, item.id, 1)}
                          disabled={index === section.items.length - 1}
                          data-move={item.id}
                          data-dir="down"
                          aria-label={t.moveDown(name)}
                          className="flex h-11 w-11 items-center justify-center rounded-control border border-ui-line text-ui-ink hover:bg-ui-subtle disabled:opacity-30"
                        >
                          <ArrowDown className="h-5 w-5" aria-hidden />
                        </button>
                      </li>
                    );
                  })}
                </ol>
                <p className="mt-3 text-sm text-ui-muted">{t.orderHint}</p>
              </>
            ) : (
          <div className="grid grid-cols-1 md:grid-cols-2 lg:grid-cols-3 gap-4 sm:gap-8">
            {section.items.map((item) => (
              <div
                key={item.id}
                className="glass-card group relative overflow-hidden flex flex-col transition-all duration-500 hover:-translate-y-1"
              >
                <div className="flex gap-4 sm:gap-6 p-4 sm:p-6">
                  <div className="relative w-20 h-20 sm:w-24 sm:h-24 rounded-panel overflow-hidden flex-shrink-0 transition-all">
                    {item.image_url ? (
                      <Image src={item.image_url} alt={pickName(item, lang)} fill className="object-cover transition-transform duration-700" />
                    ) : (
                      <div className="w-full h-full flex items-center justify-center bg-ui-bg">
                        <Package className="w-8 h-8 text-ui-input" />
                      </div>
                    )}
                    <div className="absolute inset-0" />
                    {item.is_featured ? (
                      <div className="absolute top-2 start-2 p-1.5 bg-ui-primary rounded-xl">
                        <Star className="w-3 h-3 text-ui-primary-fg fill-current" aria-label={t.recommended} />
                      </div>
                    ) : null}
                  </div>

                  <div className="flex-1 min-w-0 py-2">
                    <div className="flex items-start justify-between gap-4">
                      <div className="min-w-0">
                        <h3 className="text-lg font-semibold text-ui-heading truncate group-hover:text-ui-primary transition-colors">
                          <bdi>{pickName(item, lang)}</bdi>
                        </h3>
                        {/* The other language underneath, when there is one */}
                        {(lang === "ar" ? item.name_en && item.name_ar : item.name_ar) && (
                          <p lang={lang === "ar" ? "en" : "ar"} className="mt-1 truncate text-sm text-ui-muted">
                            <bdi>{lang === "ar" ? item.name_en : item.name_ar}</bdi>
                          </p>
                        )}
                      </div>
                      <div className="flex flex-col gap-2 transition-all duration-300 lg:translate-x-4 rtl:lg:-translate-x-4 lg:opacity-0 lg:group-hover:translate-x-0 lg:group-hover:opacity-100 lg:group-focus-within:translate-x-0 lg:group-focus-within:opacity-100">
                        <button
                          onClick={() => openEditModal(item)}
                          aria-label={t.edit(pickName(item, lang))}
                          disabled={isViewer}
                          className="w-11 h-11 lg:w-9 lg:h-9 bg-ui-surface rounded-lg flex items-center justify-center border border-ui-line hover:bg-ui-subtle transition-all disabled:opacity-50"
                        >
                          <Edit2 className="w-3.5 h-3.5 text-ui-ink" />
                        </button>
                        <button
                          onClick={() => handleDelete(item.id)}
                          aria-label={t.delete(pickName(item, lang))}
                          disabled={isViewer}
                          className="w-11 h-11 lg:w-9 lg:h-9 bg-ui-surface rounded-lg flex items-center justify-center border border-ui-line hover:bg-ui-subtle transition-all disabled:opacity-50"
                        >
                          <Trash2 className="w-3.5 h-3.5 text-ui-ink" />
                        </button>
                      </div>
                    </div>

                    <div className="mt-4 flex flex-wrap items-center justify-between gap-2">
                      <p dir="ltr" className="text-xl font-semibold text-ui-ink tabular-nums">
                        <span className="text-xs text-ui-primary me-1">{item.currency}</span>
                        {f.number(Number(item.price) || 0, { minimumFractionDigits: 2, maximumFractionDigits: 2 })}
                      </p>
                      <button
                        type="button"
                        onClick={() => toggleAvailability(item)}
                        disabled={isViewer}
                        aria-pressed={item.is_available === 0}
                        className={`min-h-9 rounded-[10px] border px-3 text-xs font-semibold transition-colors disabled:opacity-50 ${
                          item.is_available === 0
                            ? "border-ui-warning bg-ui-subtle text-ui-warning"
                            : "border-ui-line bg-ui-subtle text-ui-ink hover:bg-ui-subtle"
                        }`}
                      >
                        {item.is_available === 0 ? t.soldOutRestore : t.markSoldOut}
                      </button>
                    </div>
                  </div>
                </div>
              </div>
            ))}
          </div>
            )}
          </section>
            );
          })
        )}
      </CatalogAdminContent>

      {showModal && (
        <div className="fixed inset-0 z-50 flex items-center justify-center p-0 sm:p-8 bg-black/40 animate-in fade-in duration-300 sm:overflow-y-auto custom-scrollbar">
          <div className="glass-card w-full max-w-2xl overflow-hidden animate-in zoom-in-95 duration-500 border-ui-line my-auto flex flex-col h-[100dvh] sm:h-auto sm:max-h-[90vh] max-sm:!rounded-none max-sm:!border-0">
            <div className="shrink-0 flex items-center justify-between gap-3 px-4 py-4 sm:p-8 border-b border-ui-line bg-ui-bg">
              <div>
                <h2 className="text-xl font-semibold text-ui-heading">
                  {editingItem ? t.editDish : t.newDish}
                </h2>
                <div className="h-0.5 w-8 bg-ui-primary mt-2 rounded-full opacity-50" />
              </div>
              <button
                onClick={() => setShowModal(false)}
                className="w-11 h-11 shrink-0 bg-ui-subtle rounded-xl flex items-center justify-center text-ui-muted hover:text-ui-ink hover:bg-ui-subtle transition-all"
                aria-label={t.close}
              >
                <X className="w-5 h-5" />
              </button>
            </div>

            <div className="p-5 sm:p-8 space-y-8 flex-1 min-h-0 sm:max-h-[70vh] overflow-y-auto custom-scrollbar">
              <div className="grid grid-cols-1 md:grid-cols-2 gap-8">
                <div className="space-y-6">
                  <p className="text-sm font-medium text-ui-ink">{t.photo}</p>

                  <div className="relative">
                    {formData.image_url ? (
                      <div className="relative h-64 rounded-panel overflow-hidden border border-ui-line">
                        {/* Plain img: AI results and uploads can come from any configured storage host */}
                        {/* eslint-disable-next-line @next/next/no-img-element */}
                        <img src={formData.image_url} alt={formData.name_en || formData.name_ar || t.dishPhoto} className="h-full w-full object-cover" />
                        <button
                          type="button"
                          onClick={() => {
                            setFormData((p) => ({ ...p, image_url: "" }));
                            setImageIllustrative(false);
                          }}
                          aria-label={t.removePhoto}
                          className="absolute top-3 end-3 flex h-11 w-11 items-center justify-center rounded-control bg-ui-surface shadow-lg hover:bg-ui-subtle"
                        >
                          <X className="h-5 w-5 text-ui-ink" aria-hidden />
                        </button>
                        {imageIllustrative && (
                          <span className="absolute bottom-3 start-3 rounded-full bg-black/75 px-2.5 py-1 text-xs font-medium text-white">
                            {t.illustrative}
                          </span>
                        )}
                      </div>
                    ) : uploading ? (
                      <div className="flex flex-col items-center justify-center h-64 rounded-panel border-2 border-dashed border-ui-line bg-ui-bg" role="status">
                        <Loader2 className="w-8 h-8 text-ui-primary mb-4 animate-spin" aria-hidden />
                        <span className="text-sm font-medium text-ui-muted">{t.uploading}</span>
                      </div>
                    ) : (
                      <label className="flex flex-col items-center justify-center h-64 rounded-panel border-2 border-dashed border-ui-line bg-ui-bg cursor-pointer hover:border-ui-primary hover:bg-ui-subtle transition-colors focus-within:border-ui-primary">
                        <Upload className="w-8 h-8 text-ui-input mb-4" aria-hidden />
                        <span className="text-sm font-medium text-ui-ink">{t.uploadPhoto}</span>
                        <span className="mt-1 text-xs text-ui-muted">{t.uploadHint}</span>
                        <input type="file" accept="image/jpeg,image/png,image/webp" onChange={handleImageUpload} className="sr-only" />
                      </label>
                    )}
                  </div>
                  {uploadError && (
                    <p role="alert" className="rounded-control border border-[#F3C7C7] bg-[#FEF2F2] px-3 py-2 text-sm font-medium text-ui-danger">
                      {uploadError}
                    </p>
                  )}

                  <AiPhotoPanel
                    key={editingItem?.id || "new"}
                    slug={slug}
                    fetchWithAuth={fetchWithAuth}
                    itemId={editingItem?.id || null}
                    savedImageUrl={editingItem?.image_url || null}
                    formImageUrl={formData.image_url}
                    readOnly={isViewer}
                    onImageChange={(url, illustrative) => {
                      setFormData((p) => ({ ...p, image_url: url }));
                      setImageIllustrative(illustrative);
                      setEditingItem((current) => (current ? { ...current, image_url: url || null, image_is_illustrative: illustrative ? 1 : 0 } : current));
                      fetchData();
                    }}
                  />
                </div>

                <div className="space-y-6">
                  {/* Every plan edits Arabic and English */}
                  <div role="group" aria-label={t.contentLanguage} className="flex p-1.5 bg-ui-bg border border-ui-line rounded-control">
                      {(['en', 'ar'] as const).map((code) => (
                        <button
                          key={code}
                          type="button"
                          lang={code}
                          onClick={() => setActiveLang(code)}
                          aria-pressed={activeLang === code}
                          className={`flex-1 py-3 text-xs font-semibold transition-all rounded-xl ${activeLang === code ? "bg-ui-primary text-ui-primary-fg shadow-lg" : "text-ui-muted hover:text-ui-ink"}`}
                        >
                          {code === 'ar' ? 'العربية' : 'English'}
                        </button>
                      ))}
                  </div>

                  <div className="space-y-4">
                    {activeLang === 'en' ? (
                      <>
                        <div>
                          <label htmlFor="dish-name-en" className="text-xs font-semibold text-ui-muted block mb-2">{t.nameEn}</label>
                          <input id="dish-name-en" type="text" dir="ltr" value={formData.name_en} onChange={(e) => setFormData({ ...formData, name_en: e.target.value })} className="w-full px-6 py-4 bg-ui-bg border border-ui-input rounded-control text-ui-ink font-semibold focus:outline-none focus:border-ui-primary transition-all" />
                        </div>
                        <div>
                          <label htmlFor="dish-description-en" className="text-xs font-semibold text-ui-muted block mb-2">{t.descriptionEn}</label>
                          <textarea id="dish-description-en" dir="ltr" value={formData.description_en} onChange={(e) => setFormData({ ...formData, description_en: e.target.value })} rows={3} className="w-full px-6 py-4 bg-ui-bg border border-ui-input rounded-control text-ui-ink font-semibold focus:outline-none focus:border-ui-primary transition-all resize-none" />
                        </div>
                      </>
                    ) : (
                      <>
                        <div>
                          <label htmlFor="dish-name-ar" className="text-xs font-semibold text-ui-muted block mb-2">{t.nameAr}</label>
                          <input id="dish-name-ar" type="text" value={formData.name_ar} onChange={(e) => setFormData({ ...formData, name_ar: e.target.value })} className="w-full px-6 py-4 bg-ui-bg border border-ui-input rounded-control text-ui-ink font-semibold focus:outline-none focus:border-ui-primary transition-all" dir="rtl" />
                        </div>
                        <div>
                          <label htmlFor="dish-description-ar" className="text-xs font-semibold text-ui-muted block mb-2">{t.descriptionAr}</label>
                          <textarea id="dish-description-ar" value={formData.description_ar} onChange={(e) => setFormData({ ...formData, description_ar: e.target.value })} rows={3} className="w-full px-6 py-4 bg-ui-bg border border-ui-input rounded-control text-ui-ink font-semibold focus:outline-none focus:border-ui-primary transition-all resize-none" dir="rtl" />
                        </div>
                      </>
                    )}
                  </div>

                  <div className="grid grid-cols-1 sm:grid-cols-2 gap-4">
                    <div>
                      <label htmlFor="dish-price" className="text-xs font-semibold text-ui-muted block mb-2">{t.price}</label>
                      <input id="dish-price" type="number" dir="ltr" step="0.01" value={formData.price} onChange={(e) => setFormData((p) => ({ ...p, price: e.target.value }))} className="w-full px-6 py-4 bg-ui-bg border border-ui-input rounded-control text-ui-ink font-semibold focus:outline-none focus:border-ui-primary shadow-inner" placeholder="0.00" required />
                    </div>
                    <div>
                      <label htmlFor="dish-currency" className="text-xs font-semibold text-ui-muted block mb-2">{t.currency}</label>
                      <select id="dish-currency" value={formData.currency} onChange={(e) => setFormData((p) => ({ ...p, currency: e.target.value }))} className="w-full px-6 py-4 bg-ui-bg border border-ui-input rounded-control text-ui-ink font-semibold focus:outline-none focus:border-ui-primary transition-all appearance-none text-xs">
                        {['USD', 'LBP'].map(cur => (
                          <option key={cur} value={cur} className="bg-ui-surface">{t.currencies[cur] ?? cur}</option>
                        ))}
                      </select>
                    </div>
                  </div>

                  <div className="space-y-4">
                    <div>
                      <label htmlFor="dish-category" className="text-xs font-semibold text-ui-muted block mb-2">{t.category}</label>
                      <select id="dish-category" value={formData.category_id} onChange={(e) => setFormData((p) => ({ ...p, category_id: e.target.value }))} className="w-full px-6 py-4 bg-ui-bg border border-ui-input rounded-control text-ui-ink font-semibold focus:outline-none focus:border-ui-primary transition-all appearance-none text-xs">
                        {categories.map((cat) => (
                          <option key={cat.id} value={cat.id} className="bg-ui-surface">{pickName(cat, lang)}</option>
                        ))}
                      </select>
                    </div>

                    <label className="flex items-center gap-4 cursor-pointer group/flag">
                      <div className={`w-6 h-6 rounded-lg border border-ui-line flex items-center justify-center transition-all ${formData.is_featured ? 'bg-ui-primary border-ui-primary' : 'bg-ui-subtle group-hover:bg-white/10'}`}>
                        {formData.is_featured && <Star className="w-3.5 h-3.5 text-ui-ink fill-current" />}
                      </div>
                      <input type="checkbox" checked={formData.is_featured} onChange={(e) => setFormData((p) => ({ ...p, is_featured: e.target.checked }))} className="sr-only" />
                      <span className="text-xs font-semibold text-ui-muted group-hover:text-ui-ink transition-colors">{t.recommendedDish}</span>
                    </label>
                  </div>

                  {/* Options: sizes or choices with their own price */}
                  <fieldset className="space-y-3 rounded-panel border border-ui-line p-4">
                    <legend className="px-1 text-sm font-semibold">{t.options}</legend>
                    <p className="text-xs text-ui-muted">{t.optionsHint}</p>
                    {options.map((option, index) => (
                      <div key={option.id || `new-${index}`} className="grid grid-cols-2 gap-2 sm:grid-cols-[1fr_1fr_6rem_auto] sm:items-end">
                        <div>
                          <label htmlFor={`option-${index}-en`} className="mb-1 block text-xs font-semibold text-ui-muted">{t.optionEn(index + 1)}</label>
                          <input id={`option-${index}-en`} type="text" dir="ltr" maxLength={60} value={option.name_en} placeholder="Large" onChange={(e) => setOptions((prev) => prev.map((o, i) => (i === index ? { ...o, name_en: e.target.value } : o)))} className="min-h-11 w-full rounded-control border border-ui-input bg-ui-bg px-3" />
                        </div>
                        <div>
                          <label htmlFor={`option-${index}-ar`} className="mb-1 block text-xs font-semibold text-ui-muted">{t.optionAr(index + 1)}</label>
                          <input id={`option-${index}-ar`} type="text" dir="rtl" maxLength={60} value={option.name_ar} placeholder="كبير" onChange={(e) => setOptions((prev) => prev.map((o, i) => (i === index ? { ...o, name_ar: e.target.value } : o)))} className="min-h-11 w-full rounded-control border border-ui-input bg-ui-bg px-3" />
                        </div>
                        <div>
                          <label htmlFor={`option-${index}-price`} className="mb-1 block text-xs font-semibold text-ui-muted">{t.price}</label>
                          <input id={`option-${index}-price`} type="number" dir="ltr" min={0} step="0.01" inputMode="decimal" value={option.price} onChange={(e) => setOptions((prev) => prev.map((o, i) => (i === index ? { ...o, price: e.target.value } : o)))} className="min-h-11 w-full rounded-control border border-ui-input bg-ui-bg px-3" />
                        </div>
                        <button type="button" onClick={() => setOptions((prev) => prev.filter((_, i) => i !== index))} aria-label={t.removeOption(index + 1)} className="flex min-h-11 items-center justify-center rounded-control border border-ui-input px-3 text-sm font-semibold text-ui-danger hover:bg-ui-subtle">
                          {t.remove}
                        </button>
                      </div>
                    ))}
                    {options.length < 20 && (
                      <button type="button" onClick={() => setOptions((prev) => [...prev, { name_en: "", name_ar: "", price: "" }])} className="min-h-11 rounded-control border border-dashed border-ui-input px-4 text-sm font-semibold text-ui-primary hover:bg-ui-subtle">
                        {t.addOption}
                      </button>
                    )}
                    {options.length > 0 && <p className="text-xs text-ui-muted">{t.optionsPriceHint}</p>}
                  </fieldset>

                  {/* Dietary tags: the restaurant's own claim */}
                  <fieldset className="rounded-panel border border-ui-line p-4">
                    <legend className="px-1 text-sm font-semibold">{t.dietary}</legend>
                    <div className="grid grid-cols-2 gap-2">
                      {DIETARY_CODES.map((code) => (
                        <label key={code} className="flex min-h-11 cursor-pointer items-center gap-3">
                          <input type="checkbox" checked={dietary.includes(code)} onChange={(e) => setDietary((prev) => (e.target.checked ? [...prev, code] : prev.filter((c) => c !== code)))} className="h-5 w-5" />
                          {/* Both languages: guests see the tag in theirs */}
                          <span className="text-sm">
                            {DIETARY_LABELS[code][lang]} · <span lang={lang === "ar" ? "en" : "ar"}>{DIETARY_LABELS[code][lang === "ar" ? "en" : "ar"]}</span>
                          </span>
                        </label>
                      ))}
                    </div>
                  </fieldset>

                  {/* Allergens: never guessed; unknown until the owner confirms */}
                  <fieldset className="rounded-panel border border-ui-line p-4">
                    <legend className="px-1 text-sm font-semibold">{t.allergens}</legend>
                    <label className="flex min-h-11 cursor-pointer items-center gap-3">
                      <input type="checkbox" checked={allergensChecked} onChange={(e) => setAllergensChecked(e.target.checked)} className="h-5 w-5" />
                      <span className="text-sm font-semibold">{t.allergensChecked}</span>
                    </label>
                    <p className="mt-1 text-xs text-ui-muted">{t.allergensHint}</p>
                    <div className="mt-3 grid grid-cols-2 gap-2">
                      {ALLERGEN_CODES.map((code) => (
                        <label key={code} className={`flex min-h-11 items-center gap-3 ${allergensChecked ? "cursor-pointer" : "opacity-50"}`}>
                          <input type="checkbox" disabled={!allergensChecked} checked={allergensChecked && allergens.includes(code)} onChange={(e) => setAllergens((prev) => (e.target.checked ? [...prev, code] : prev.filter((c) => c !== code)))} className="h-5 w-5" />
                          <span className="text-sm">{ALLERGEN_LABELS[code][lang]}</span>
                        </label>
                      ))}
                    </div>
                    {allergensChecked && allergens.length === 0 && (
                      <p className="mt-2 text-xs text-ui-muted">{t.noAllergens}</p>
                    )}
                  </fieldset>

                  {saveError && (
                    <p role="alert" className="rounded-control border border-ui-danger bg-ui-subtle px-4 py-3 text-sm text-ui-danger">{saveError}</p>
                  )}
                </div>
              </div>
            </div>

            <div className="shrink-0 flex gap-3 sm:gap-4 px-4 pt-4 pb-[max(1rem,env(safe-area-inset-bottom))] sm:p-8 border-t border-ui-line bg-ui-bg">
              <button
                onClick={() => setShowModal(false)}
                className="flex-1 px-5 sm:px-8 py-4 bg-ui-subtle text-ui-muted rounded-control hover:text-ui-ink hover:bg-ui-subtle transition-all text-xs font-semibold"
              >
                {t.cancel}
              </button>
              <button
                onClick={handleSave}
                disabled={saving || isViewer}
                className="flex-1 px-5 sm:px-8 py-4 bg-ui-primary text-ui-primary-fg rounded-control font-semibold text-xs disabled:opacity-30 disabled:cursor-not-allowed transition-all flex items-center justify-center gap-3 group/save"
              >
                {saving ? (
                  <>
                    <Loader2 className="w-4 h-4 animate-spin" />
                    {t.saving}
                  </>
                ) : (
                  <>
                    {t.saveDish}
                    <ArrowRight className="w-4 h-4 transition-transform rtl:-scale-x-100 group-hover/save:translate-x-1 rtl:group-hover/save:-translate-x-1" />
                  </>
                )}
              </button>
            </div>
          </div>
        </div>
      )}
    </>
  );
}

export default function ItemsPage() {
  return (
    <CatalogAdminShell>
      <ItemsPageContent />
    </CatalogAdminShell>
  );
}
